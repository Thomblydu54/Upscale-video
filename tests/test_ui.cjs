/* Tests d'interface : extensions + non-régression des finitions / FPS / cartes. */
'use strict';
const { JSDOM } = require('jsdom');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const ui = path.join(__dirname, '..', 'ui');
const html = fs.readFileSync(path.join(ui, 'index.html'), 'utf8').replace(/<script[\s\S]*?<\/script>/g, '');
const dom = new JSDOM(html, { url: 'http://example.test/?demo=1', pretendToBeVisual: true, runScripts: 'outside-only' });
const w = dom.window;
const errors = [];
w.addEventListener('error', (e) => errors.push(e.message));
w.HTMLCanvasElement.prototype.getContext = () => new Proxy({}, { get: (t, k) => k === 'getImageData' ? () => ({ data: new Uint8ClampedArray(4) }) : k === 'createLinearGradient' || k === 'createRadialGradient' ? () => ({ addColorStop() {} }) : () => {} });
w.HTMLCanvasElement.prototype.toDataURL = () => 'data:image/png;base64,';
w.Element.prototype.scrollIntoView = () => {};
w.matchMedia = () => ({ matches: false, addEventListener() {}, addListener() {} });
w.confirm = () => true;
w.eval(['mock.js', 'extensions.js', 'app.js'].map((p) => fs.readFileSync(path.join(ui, p), 'utf8')).join('\n;\n'));
const $ = (s) => w.document.querySelector(s);
const $$ = (s) => [...w.document.querySelectorAll(s)];
const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms));
async function until(fn) { for (let i = 0; i < 100; i++) { if (fn()) return; await sleep(50); } throw new Error('Délai dépassé'); }
(async () => {
  await until(() => w.__appReady);
  assert.equal($$('.model-card').length, 5);
  assert.equal($('#remoteDestination').hidden, true);
  $('#extensionsBtn').click();
  assert.equal($('#extensionsModal').hidden, false);
  assert.equal($('#rConsent').checked, false);
  assert.equal($('#rSetupStartup').checked, false);
  assert.equal($('#extensionWelcome').hidden, false);
  $('[data-install]').click();
  await until(() => !$('#remoteSetup').hidden);
  $('#rActivate').click(); // autorisation manquante : pas d'activation
  await sleep(100);
  assert.equal($('#rService').hidden, true);
  $('#rConsent').checked = true;
  $('#rPort').value = '1234.5'; $('#rActivate').click(); await sleep(100);
  assert.equal($('#rService').hidden, true);
  $('#rPort').value = '38443'; $('#rActivate').click();
  await until(() => !$('#rService').hidden);
  assert.equal($('#rConsent').checked, false);
  assert.equal($('#rStartup').checked, false);
  assert.equal($('#remoteDestination').hidden, false);
  $('#remoteTarget').value = 'demo-worker'; $('#remoteTarget').dispatchEvent(new w.Event('change'));
  await until(() => $('#privacyLabel').textContent === 'Vos PC · gratuit');
  assert.match($('#remoteTargetNote').textContent, /GPU distant/);
  $('#rPair').click(); await until(() => !$('#rPairBox').hidden);
  assert.ok($('#rPairCode').value);
  $('#extensionsClose').click();
  assert.equal($('#extensionsModal').hidden, true);
  assert.equal($('#rPairCode').value, '');
  // Les anciennes options restent à leur place et gardent leur comportement.
  $('#finishOn').click(); await sleep(100);
  $('#finishPresets button[data-v="auto"]').click(); await sleep(100);
  assert.equal($('#finAuto').hidden, false);
  assert.equal($$('.fin-slider').filter((el) => !el.hidden).length, 0);
  $('#finishPresets button[data-v="cinema"]').click(); await sleep(100);
  assert.equal($('#finAuto').hidden, true);
  assert.equal($$('.fin-slider').filter((el) => !el.hidden).length, 5);
  $('#interpolation button[data-v="custom"]').click(); await sleep(100);
  $('#interpFps').value = '120'; $('#interpFps').dispatchEvent(new w.Event('change')); await sleep(100);
  assert.equal($('#interpFps').value, '120');
  $('#interpFps').value = '59,94'; $('#interpFps').dispatchEvent(new w.Event('change')); await sleep(100);
  assert.equal($('#interpFps').classList.contains('bad'), true);
  $('#interpolation button[data-v="x2"]').click(); await sleep(150);
  assert.equal($('#fpsCustom').hidden, true);
  await until(() => $$('.card').length >= 4);
  assert.equal($$('.kind-badge.img').filter((el) => !el.hidden).length, 1);
  assert.deepEqual(errors, []);
  console.log('OK : catalogue, installation, consentement, démarrage opt-in, appairage, destination, finitions Auto, FPS entiers et cartes images.');
  dom.window.close();
})().catch((error) => { console.error(error); dom.window.close(); process.exitCode = 1; });
